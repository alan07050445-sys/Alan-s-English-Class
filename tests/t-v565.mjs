// v565 手寫題批改放寬：內容達標給高分；拼字文法小錯每 3 個才扣 1 分（有上限）
import fs from 'fs'; import vm from 'vm';
const data = fs.readFileSync(new URL('../data.js', import.meta.url), 'utf8');
const dash = fs.readFileSync(new URL('../components-dashboard.jsx', import.meta.url), 'utf8');
const qm = fs.readFileSync(new URL('../components-quiz-mode.jsx', import.meta.url), 'utf8');
let pass = 0, fail = 0;
const ok = (m, c) => { if (c) { pass++; console.log('  ✅', m); } else { fail++; console.log('  ❌', m); } };
const g = (a, b) => data.slice(data.indexOf(a), data.indexOf(b, data.indexOf(a)));
const sb = {}; vm.createContext(sb);
vm.runInContext(g('const EXAM_RUBRIC = [', 'const AI_RUBRIC_SYS') + '\nthis.pts = examRubricPoints; this.of = examRubricOf; this.ded = examErrDeduct; this.part = examRubricPart; this.RULE = EXAM_ERR_RULE;', sb);
console.log('\n【小錯怎麼扣：每 3 個扣 1 分，不是一個扣一分】');
ok('0、1、2 個小錯不扣', [0, 1, 2].every(n => sb.ded(n, 'summary') === 0));
ok('3、4、5 個小錯扣 1 分', [3, 4, 5].every(n => sb.ded(n, 'summary') === 1));
ok('摘要題最多扣 1 分（頂多扣一分）', sb.ded(30, 'summary') === 1);
ok('其他寫作題每 3 個扣 1 分，最多扣 2 分', sb.ded(6, 'writing') === 2 && sb.ded(30, 'writing') === 2 && sb.ded(30, 'basic') === 2);
const R = sb.of({ rubricSet: 'summary' });
const full = { begin: 2, middle: 2, end: 2, order: 2, sent: 1, own: 1 };
ok('內容全對、2 個小錯 → 10 分', sb.pts({ ...full, _errN: 2 }, 10, R.max, R.criteria, 'summary') === 10);
ok('內容全對、5 個小錯 → 9 分（只扣 1 分）', sb.pts({ ...full, _errN: 5 }, 10, R.max, R.criteria, 'summary') === 9);
ok('內容全對、30 個小錯 → 還是 9 分（上限）', sb.pts({ ...full, _errN: 30 }, 10, R.max, R.criteria, 'summary') === 9);
ok('沒給過小錯個數的舊分數照舊', sb.pts(full, 10, R.max, R.criteria, 'summary') === 10);
ok('不會扣到負數', sb.pts({ begin: 0, middle: 0, end: 0, order: 0, sent: 0, own: 0, _errN: 9 }, 10, R.max, R.criteria, 'summary') === 0);
ok('「還沒改」仍然是 null（有小錯個數也一樣）', sb.pts({ _errN: 5 }, 10, R.max, R.criteria, 'summary') === null);
ok('整大題加總也套用', sb.part({ pts: 10, questions: [{ q: 'x', pts: 10 }], rubricSet: 'summary' }, { 0: { ...full, _errN: 4 } }).got === 9);
console.log('\n【提示詞：大方，但不亂給】');
ok('達到標準就給最高分', /BE GENEROUS/.test(data) && /give the TOP score whenever the child clearly does what the criterion asks/.test(data));
ok('內容不因拼字文法扣分', /Never lower a content score because of spelling, grammar/.test(data));
ok('起因／經過／結果寫到就滿分', /cause \(起因\), what happened \(經過\) and the result \(結果\)/.test(data));
ok('沒寫到的不能亂給（大方 ≠ 編造）', /Generous is NOT the same as inventing/.test(data));
ok('「達標」＝最高等第（寫作七項不再把達標放中間）', /"Meets the standard" = the TOP score/.test(data) && /LENIENT_BAND_TEXT/.test(data));
ok('小錯另外列、不進準則', /SPELLING & GRAMMAR are NOT part of the scores above/.test(data));
ok('小錯要「接地」：AI 說的錯必須是孩子真的寫過的字', /小錯清單也要「接地」/.test(data) && /flat\(ans\)\.indexOf\(k\) < 0/.test(data));
ok('文法那一項不重複扣（小錯 ≤5 給最高）', /gc && out\.grammar && out\._errN <= 5/.test(data));
ok('孩子讀的文章一起給 AI（才知道起因經過結果是什麼）', /THE PASSAGE THE CHILD READ/.test(data) && /passage: w\.passage/.test(dash) && /passage: passageOf\(pp\)/.test(qm));
ok('回覆空間夠放小錯清單（不再截斷）', /_gnCall\(sys, msg, 1400\)/.test(data));
console.log('\n【老師畫面】');
ok('小錯個數可以自己改，並顯示扣幾分', /mk-err/.test(dash) && /examErrDeduct\(c\._errN, w\.rubricSet\)/.test(dash));
ok('有「這一大題全部 AI 先改」', /這一大題全部 AI 先改/.test(dash));
ok('學生看得到「有幾個小錯、扣幾分」', /個小錯，扣/.test(qm));
console.log(fail ? `\n❌ t-v565：${pass} 過 / ${fail} 失敗` : `\n✅ t-v565：${pass} 過 / 0 失敗`);
process.exit(fail ? 1 : 0);
