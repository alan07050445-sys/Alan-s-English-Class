// v607 考卷：作答自動保存＋交卷後解析
import fs from 'fs'; import vm from 'vm';
const data = fs.readFileSync(new URL('../data.js', import.meta.url), 'utf8');
const qm = fs.readFileSync(new URL('../components-quiz-mode.jsx', import.meta.url), 'utf8');
const ed = fs.readFileSync(new URL('../components-editor.jsx', import.meta.url), 'utf8');
let pass = 0, fail = 0;
const ok = (m, c) => { if (c) { pass++; console.log('  ✅', m); } else { fail++; console.log('  ❌', m); } };
const grab = (a, b) => data.slice(data.indexOf(a), data.indexOf(b, data.indexOf(a)));
const store = {};
const sb = { localStorage: { getItem: k => (k in store ? store[k] : null), setItem: (k, v) => { store[k] = v; }, removeItem: k => { delete store[k]; } }, window: { _currentUser: { uid: 'u1' } }, Date, JSON, Object, Array, String, Math };
vm.createContext(sb);
const pn = grab('function examPartN', '\nfunction ', data.indexOf('function examPartN') + 5);
vm.runInContext(pn + '\n' + grab('const EXAM_DRAFT_TTL', '/* ══ v607 ② ') + '\nthis.L=examDraftLoad;this.S=examDraftSave;this.C=examDraftClear;this.H=examDraftHas;this.G=examDraftSig;', sb);
const item = { sections: [{ parts: [{ kind: 'quiz', title: 'A', questions: [{}, {}] }] }] };
console.log('\n【草稿】');
ok('空答案不存', sb.S('k', item, { ans: {}, mood: null }) === false && Object.keys(store).length === 0);
ok('有答案就存、讀得回來', sb.S('k', item, { ans: { '0_0': [1, 0] }, mood: null }) && JSON.stringify(sb.L('k', item).ans) === '{"0_0":[1,0]}');
ok('卷子改了（題數不同）就不套用舊草稿', sb.L('k', { sections: [{ parts: [{ kind: 'quiz', title: 'A', questions: [{}, {}, {}] }] }] }) === null);
ok('換帳號看不到別人的', (sb.window._currentUser.uid = 'u2', sb.L('k', item) === null));
sb.window._currentUser.uid = 'u1';
ok('超過 14 天就丟', (() => { const key = Object.keys(store)[0]; const d = JSON.parse(store[key]); d.at -= 15 * 864e5; store[key] = JSON.stringify(d); return sb.L('k', item) === null; })());
sb.S('k', item, { ans: { a: 'x'.repeat(200000), b: 'hi' } });
ok('畫圖那種超大字串不存，其他照存', (() => { const d = sb.L('k', item); return d && d.ans.b === 'hi' && !('a' in d.ans); })());
sb.C('k'); ok('清掉就沒了', sb.L('k', item) === null);
console.log('\n【接線】');
ok('ExamPlayer 從草稿起頭並顯示「從頭開始」', /examDraftLoad\(progressKey, item\)/.test(qm) && /restartFresh/.test(qm) && /ex-resume/.test(qm));
ok('離開頁面時補存', /visibilitychange[\s\S]{0,200}pagehide|pagehide/.test(qm));
ok('交卷存好成績後才清草稿', /saveQuizModeCompletion\(progressKey, item, \{\s*\n\s*doneCount: r\.parts[\s\S]{0,400}examDraftClear\(progressKey\)/.test(qm));
console.log('\n【解析】');
ok('清洗不再洗掉 explain／quote', /explain \? \{ explain \}/.test(data) && /quote \? \{ quote \}/.test(data));
ok('quote 要逐字出現在文章才收', /hay\.indexOf\(_exNorm\(quote\)\) >= 0/.test(data));
ok('AI 不同意答案時只回報、不寫解析', /it\.disagree\) \{ disputed\.push/.test(data));
ok('讀考卷時順便補解析，且壞掉不擋', /examExplain\(secs\)/.test(data));
ok('交卷後顯示正確答案／解析／依據／範例', /ex-why-a/.test(qm) && /ex-why-q/.test(qm) && /ex-sample/.test(qm));
ok('只有交卷後才顯示（sent）', /\{sent && \(\s*\n\s*<div className=\{'ex-why'/.test(qm));
ok('解析讀回覆時要找 text 區塊（模型第一塊是 thinking）', /examExplain[\s\S]{0,2600}filter\(b => b && b\.type === 'text'\)/.test(data));
ok('編輯器有「AI 補上解析」按鈕', /aiExplainExam/.test(ed) && /AI 補上解析/.test(ed));
console.log(fail ? `\n❌ t-v607：${pass} 過 / ${fail} 失敗` : `\n✅ t-v607：${pass} 過 / 0 失敗`);
process.exit(fail ? 1 : 0);
