// v620 VCe 卷：單字表格圈字（程式自己數要圈幾個）＋自己選字造字造句
import fs from 'fs';
const data = fs.readFileSync(new URL('../data.js', import.meta.url), 'utf8');
const qm = fs.readFileSync(new URL('../components-quiz-mode.jsx', import.meta.url), 'utf8');
let pass = 0, fail = 0;
const ok = (m, c) => { if (c) { pass++; console.log('  ✅', m); } else { fail++; console.log('  ❌', m); } };
const stub = new Proxy(function () {}, { get: () => stub, apply: () => stub, construct: () => stub });
const W = {};
new Function('window', 'document', 'firebase', 'localStorage', 'fetch', data)(W, { documentElement: { classList: { toggle: () => {} } } }, stub, { getItem: () => null, setItem() {}, removeItem() {} }, fetch);
console.log('\n【Part A 單字表格】');
const grid = 'together outside impose cyclone imitate contribute pause teach thirsty Internet satisfied evaporate calendar sequence tissue advertise emphasize fascinate survive bathroom';
const real = grid.split(' ').filter(w => W.wsCheck(w, { kind: 'vce', args: [] }) === true);
ok('VCe 檢查器從表格裡挑出的就是那 10 個（pause／tissue／sequence 是冒牌貨）', real.join() === 'outside,impose,cyclone,imitate,contribute,evaporate,advertise,emphasize,fascinate,survive');
const circ = { kind: 'circle', check: 'vce', passage: grid, need: 10, pts: 10 };
const good = W.examScorePart(circ, real);
ok('圈對 10 個＝滿分', good.right === 10 && good.got === 10);
ok('圈到冒牌貨要扣分（不能整張全圈）', W.examScorePart(circ, grid.split(' ')).right === 0);
ok('表格欄數存得住、文字來回不失真', (() => { const b = W.examParsePart('circle', W.examPartText({ kind: 'circle', check: 'vce', passage: 'a b', cols: 4 })); return b.cols === 4 && b.check === 'vce' && b.passage === 'a b'; })());
console.log('\n【Part C 自己選字造句】');
const part = { kind: 'vcewrite', groups: ['a', 'i', 'o', 'u'], per: 2, minWords: 3, pts: 8, exclude: grid.toLowerCase().split(' ') };
ok('題數＝母音數×每個幾個', W.examPartN(part) === 8);
const S = (word, sentence) => ({ word, sentence });
const ans = [S('cake', 'I like the cake.'), S('plane', 'The plane is fast.'), S('bike', 'I ride my bike.'), S('time', 'It is time now.'),
             S('home', 'I go home.'), S('nose', 'My nose is cold.'), S('cube', 'The cube is red.'), S('imitate', 'I imitate a bird.')];
const r = W.examScorePart(part, ans);
ok('對的算對', r.right === 7 && r.detail[7].ok === false);
ok('Part A 的字不能用（Long a 寫 imitate）', /Part A/.test(W.examScorePart(part, [S('imitate', 'I imitate a bird.')]).detail[0].why.join()));
ok('母音要對（Long a 寫 bike 不行）', W.examScorePart(part, [S('bike', 'I ride my bike.')]).detail[0].why.some(x => /長母音/.test(x)));
ok('同一個字不能用兩次', W.examScorePart(part, [S('cake', 'A big cake.'), S('cake', 'A small cake.')]).detail[1].ok === false);
ok('不是 VCe 的字不行、沒造句不行、句子沒用到那個字不行', (() => { const d = W.examScorePart(part, [S('cat', 'A cat sat.'), S('cake', ''), S('lake', 'The sky is blue.')]).detail; return d.every(x => !x.ok) && d[0].why.some(x => /VCe/.test(x)) && d[1].why.includes('沒有造句') && d[2].why.some(x => /沒有用到/.test(x)); })());
ok('句子太短不給過', W.examScorePart(part, [S('cake', 'Cake.')]).detail[0].ok === false);
ok('文字來回不失真', (() => { const b = W.examParsePart('vcewrite', W.examPartText(part)); return b.groups.join('') === 'aiou' && b.per === 2 && b.exclude.length === part.exclude.length; })());
console.log('\n【讀考卷接線】');
ok('提示詞教 circle 吃單字表格、教 vcewrite', /A WORD GRID \/ LIST counts too/.test(data) && /"vcewrite"— /.test(data));
ok('沒印要圈幾個時由程式自己數', /need = \(passage\.match/.test(data));
ok('Part A 的字自動接給自己選字的那一題（短文不算）', /!\/\[\.!\?\]\/\.test\(String\(pt\.passage/.test(data));
ok('「不要再有做不到的題目」：提示詞禁止跳過＋程式把收不進來的改收成問答題', /NEVER SKIP A QUESTION/.test(data) && /先收成「問答題（老師改）」/.test(data));
ok('題型有登記、有學生畫面', W.EXAM_KINDS.vcewrite && W.EXAM_KINDS.vcewrite.auto && /pt\.kind === 'vcewrite'/.test(qm));
console.log(fail ? `\n❌ t-v620：${pass} 過 / ${fail} 失敗` : `\n✅ t-v620：${pass} 過 / 0 失敗`);
process.exit(fail ? 1 : 0);
