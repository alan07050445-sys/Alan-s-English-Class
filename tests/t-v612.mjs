// v612 Trick or Treat：獎品由帳號反算（不可重抽、不可偽造）、只認活動期間
import fs from 'fs';
const data = fs.readFileSync(new URL('../data.js', import.meta.url), 'utf8');
const shell = fs.readFileSync(new URL('../components-shell.jsx', import.meta.url), 'utf8');
const app = fs.readFileSync(new URL('../app.jsx', import.meta.url), 'utf8');
const dash = fs.readFileSync(new URL('../components-dashboard.jsx', import.meta.url), 'utf8');
let pass = 0, fail = 0;
const ok = (m, c) => { if (c) { pass++; console.log('  ✅', m); } else { fail++; console.log('  ❌', m); } };
const stub = new Proxy(function () {}, { get: () => stub, apply: () => stub, construct: () => stub });
const W = {};
new Function('window', 'document', 'firebase', 'localStorage', 'fetch', data)(W, { documentElement: { classList: { toggle: () => {} } } }, stub, { getItem: () => null, setItem() {}, removeItem() {} }, fetch);
const at = (s) => new Date(s).getTime();
console.log('\n【獎品】');
const prizes = Array.from({ length: 4000 }, (_, i) => W.treatPrize('uid' + i, 'hw2026'));
ok('同一個人永遠同一個數字（重整不會重抽）', W.treatPrize('abc', 'hw2026') === W.treatPrize('abc', 'hw2026'));
ok('全部落在 100~500，而且是 50 的倍數', prizes.every(p => p >= 100 && p <= 500 && p % 50 === 0));
ok('每一檔都有人抽得到（4000 人）', [100, 150, 200, 250, 300, 350, 400, 450, 500].every(v => prizes.includes(v)));
const avg = prizes.reduce((a, b) => a + b, 0) / prizes.length;
ok(`平均約 190（實測 ${avg.toFixed(0)}）——這是真的會花的錢`, avg > 170 && avg < 215);
ok('100 是最多的、500 是最少的', prizes.filter(p => p === 100).length > prizes.filter(p => p === 300).length && prizes.filter(p => p === 500).length < prizes.filter(p => p === 400).length);
console.log('\n【期間】');
ok('10/30 還不能領', !W.treatOpenAt('hw2026', at('2026-10-30T23:59:00')));
ok('10/31 00:00 開始能領（倒數歸零那一刻）', W.treatOpenAt('hw2026', at('2026-10-31T00:00:00')));
ok('11/02 晚上還能領（週末沒上線的孩子）', W.treatOpenAt('hw2026', at('2026-11-02T23:30:00')));
ok('11/03 就結束了', !W.treatOpenAt('hw2026', at('2026-11-03T00:00:01')));
ok('不存在的活動不能領', !W.treatOpenAt('nope', at('2026-10-31T10:00:00')));
console.log('\n【星星是算出來的】');
const good = { hw2026: at('2026-10-31T09:00:00') };
ok('領過 → 加上那個人固定的獎品', W.computeTreatStars(good, 'u1').total === W.treatPrize('u1', 'hw2026'));
ok('寫進去的數字沒人讀：多塞一個 amount 沒用', W.computeTreatStars({ hw2026: good.hw2026, amount: 500, hw2026amount: 500 }, 'u1').total === W.treatPrize('u1', 'hw2026'));
ok('時間不在期間內的紀錄不算（主控台亂寫的）', W.computeTreatStars({ hw2026: at('2026-09-01T09:00:00') }, 'u1').total === 0);
ok('寫 true／字串／負數都不算', [true, 'x', -5, 0, null].every(v => W.computeTreatStars({ hw2026: v }, 'u1').total === 0));
ok('沒領過 → 0，沒有 treat 欄位也不爆', W.computeTreatStars(null, 'u1').total === 0 && W.computeTreatStars({}, 'u1').total === 0);
ok('星星明細有一行南瓜獎勵', W.computeTreatStars(good, 'u1').entries[0].note.includes('南瓜'));
console.log('\n【接線】');
ok('領取只寫「時間」，不寫獎品數字', /const upd = \{ \[`treat\.\$\{key\}`\]: Date\.now\(\) \}/.test(data));
ok('已領過不會蓋掉第一次的時間', /if \(had\) return false/.test(data));
ok('雲端讀回的第四個參數是 treat', /d\.treat \|\| null\);/.test(data));
ok('header 星星、星星面板、老師後台三處都加了', /computeTreatStars\(myTreat, user\.uid\)/.test(app) && /computeTreatStars\(treat, user/.test(shell) && /computeTreatStars\(st\.treat, st\.uid\)/.test(dash));
ok('老師後台順便補上訂正錯題的星星（以前少算）', /computeFixedStars\(st\.fixed\)/.test(dash) && /fixed: d\.fixed \|\| null/.test(data));
ok('雲端沒回來（undefined）不跳南瓜', /treat === undefined/.test(shell));
ok('預覽模式不寫雲端', /preview \? Promise\.resolve\(\)/.test(shell));
ok('app 有掛上元件', /window\.TrickOrTreat/.test(app));
console.log(fail ? `\n❌ t-v612：${pass} 過 / ${fail} 失敗` : `\n✅ t-v612：${pass} 過 / 0 失敗`);
process.exit(fail ? 1 : 0);
